import {createRequire} from 'node:module';
import {readFileSync,writeFileSync} from 'node:fs';
import {isDeepStrictEqual} from 'node:util';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('..',import.meta.url)).replace(/\/$/,'');
const require=createRequire(root+'/frontend/package.json');
const {chromium,expect}=require('@playwright/test');
const AxeBuilder=require('@axe-core/playwright').default;
const link=new URL(readFileSync(root+'/var/interface-access.url','utf8').trim());
if(link.origin!=='http://127.0.0.1:8765')throw Error('Unexpected origin');
const old=JSON.parse(readFileSync(root+'/var/validation/applications-before-install.json','utf8'));
const checks=['cpu_w','gpu_w'].map(metric=>JSON.parse(readFileSync(root+'/var/validation/installed-applications-'+metric+'.json','utf8')));
const browser=await chromium.launch({headless:true});
try{
 const context=await browser.newContext({baseURL:link.origin,viewport:{width:1440,height:1000},reducedMotion:'reduce'});
 const login=await context.request.post('/api/session',{headers:{Origin:link.origin,Authorization:'Bearer '+new URLSearchParams(link.hash.slice(1)).get('access')}});
 expect(login.ok()).toBeTruthy();
 const get=async path=>{const response=await context.request.get(path);expect(response.ok()).toBeTruthy();return response.json()};
 const settings=await get('/api/settings'),before=await get('/api/ai/settings');
 expect(settings.version).toBe('0.6.0');expect(before.authorized_total_usd).toBe(5);
 expect(isDeepStrictEqual(settings.collector.values,old.collector)).toBeTruthy();
 expect(isDeepStrictEqual(settings.tariffs,old.tariffs)).toBeTruthy();
 expect(isDeepStrictEqual(before.limits,old.ai.limits)).toBeTruthy();
 const data=await get('/api/overview?hours=1');
 const selected=[...data.processes.snapshots].reverse().find(s=>s.context.applications?.some(g=>g.methods.includes('parent_rule')));
 expect(selected).toBeTruthy();
 const group=selected.context.applications.find(g=>g.methods.includes('parent_rule'));
 const child=group.entries.find(e=>e.application.method==='parent_rule');
 const page=await context.newPage(),errors=[],mutations=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.url().includes('/api/')&&r.method()!=='GET')mutations.push({method:r.method(),path:new URL(r.url()).pathname})});
 await page.goto('/?view=processes');
 await expect(page).toHaveTitle('Vatilume · Energia e sinais do seu PC');
 await expect(page.getByRole('button',{name:'Aplicativos',exact:true})).toHaveAttribute('aria-pressed','true');
 await page.getByLabel('Atualizar automaticamente',{exact:true}).uncheck();
 await page.getByLabel('Varredura',{exact:true}).selectOption(String(selected.sample_id));
 const table=page.getByRole('region',{name:'Leituras de processos',exact:true});
 const row=table.locator('tbody tr').filter({hasText:group.name}).first();
 await row.locator('summary').click();
 await expect(row).toContainText(child.name);
 await expect(row).toContainText('Parentesco registrado');
 await expect(row).toContainText('Vínculo com o aplicativo principal');
 await page.getByRole('button',{name:'Processos técnicos',exact:true}).click();
 await expect(table).toContainText('PID '+child.pid);
 await expect(table).toContainText(child.name);
 await page.getByRole('button',{name:'Aplicativos',exact:true}).click();
 await page.getByLabel('Comparar com',{exact:true}).selectOption('gpu_w');
 await expect(page.locator('.process-peak').first()).toBeVisible();
 await page.getByLabel('Comparar com',{exact:true}).selectOption('cpu_w');
 const sizes=[];
 for(const width of [1440,390]){
  await page.setViewportSize({width,height:1000});
  await expect.poll(()=>page.locator('.sidebar').evaluate(el=>el.getBoundingClientRect().right)).toBeLessThanOrEqual(width<640?0:240);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBeFalsy();
  const axe=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  expect(axe.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)}))).toEqual([]);
  await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0)});
  await page.screenshot({path:root+`/var/validation/installed-applications-${width}.png`,fullPage:true,animations:'disabled'});
  sizes.push({width,overflow:false,axe_violations:0});
 }
 await page.setViewportSize({width:1440,height:1000});
 const reports=[];
 for(const check of checks){
  const record=await get('/api/ai/analyses/'+check.analysis_id);
  expect(record.report.validator_version).toBe('applications-1');
  await page.goto('/?view=ai');
  await page.locator('.ai-history-item').filter({hasText:record.question}).first().click();
  await expect(page.locator('.ai-answer')).toContainText('Coincidência temporal');
  await expect(page.locator('.ai-answer-text')).toHaveText(record.report.answer.text);
  const match=record.report.answer.values.peak.matches[0];
  expect(record.report.answer.text).toContain(match.name);
  await page.getByRole('button',{name:'Conferir cálculo e dados',exact:true}).click();
  const evidence=page.locator('.ai-evidence-area');
  await expect(evidence).toContainText(match.name);
  await expect(evidence).toContainText('Somente processos retidos');
  await expect(evidence.getByRole('region',{name:'Processos com intervalos sobrepostos',exact:true}).first()).toContainText('A00');
  const csv=evidence.getByRole('link',{name:'Baixar evidências de processos (CSV)',exact:true});
  const csvResponse=await context.request.get(await csv.getAttribute('href'));
  expect(csvResponse.ok()).toBeTruthy();
  const content=await csvResponse.text();
  expect(content).toContain('application_method');expect(content).toContain('previous_cpu_ticks');
  await page.evaluate(()=>{document.activeElement?.blur();window.scrollTo(0,0)});
  await page.screenshot({path:root+`/var/validation/installed-applications-ai-${check.metric}.png`,fullPage:true,animations:'disabled'});
  reports.push({metric:check.metric,id:record.id,kind:record.report.answer.kind,evidence:true,csv:true});
 }
 const after=await get('/api/ai/settings'),finalSettings=await get('/api/settings');
 expect(after.usage.total_usd).toBe(before.usage.total_usd);
 expect(isDeepStrictEqual(settings.collector.values,finalSettings.collector.values)).toBeTruthy();
 expect(isDeepStrictEqual(settings.tariffs,finalSettings.tariffs)).toBeTruthy();
 expect(errors).toEqual([]);expect(mutations).toEqual([]);
 const result={result:'passed',version:settings.version,local_grouping:true,parent_member_details:true,technical_view:true,sizes,reports,configuration_preserved:true,tariffs_preserved:true,smaller_limits_preserved:true,budget_unchanged_during_navigation:true,estimated_total_usd:after.usage.total_usd,authorized_total_usd:after.authorized_total_usd,page_errors:errors,mutations,observed_utc_ms:Date.now()};
 writeFileSync(root+'/var/validation/installed-applications-browser.json',JSON.stringify(result,null,2)+'\n');
 console.log(JSON.stringify(result,null,2));
}finally{await browser.close()}
