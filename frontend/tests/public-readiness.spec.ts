import {test,expect} from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
const origin='http://127.0.0.1:8767'

test.use({baseURL:origin})
test.beforeEach(async({context})=>{
  const r=await context.request.post('/api/session',{headers:{Origin:origin,Authorization:'Bearer synthetic-public-test'}})
  expect(r.ok()).toBeTruthy()
})
test('legal notices, private scope and mobile keyboard access',async({page})=>{
  await page.goto('/?view=about')
  await expect(page.getByRole('heading',{name:'Sobre o Vatilume'})).toBeVisible()
  await expect(page.getByText('Copyright © 2026 APFS.',{exact:false})).toBeVisible()
  const license=page.getByRole('link',{name:'Licença GPL-3.0'})
  await license.focus();await expect(license).toBeFocused()
  const document=await page.request.get('/legal/license')
  expect(await document.text()).toContain('GNU GENERAL PUBLIC LICENSE')
  for(const width of [1440,390]){
    await page.setViewportSize({width,height:1100})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBeFalsy()
    const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
    expect(audit.violations.map(v=>v.id)).toEqual([])
    await page.screenshot({path:test.info().outputPath(`about-${width}.png`),fullPage:true})
  }
})
test('new user explicitly chooses budget without a paid request',async({page,context})=>{
  await context.request.put('/api/ai/settings',{headers:{Origin:origin},data:{enabled:false,per_analysis_usd:.05,daily_usd:1,monthly_usd:2,authorized_total_usd:0}})
  await page.goto('/?view=ai')
  await page.getByText('Ajustar limites e pausar',{exact:true}).click()
  const field=page.getByLabel('Limite acumulado (US$)',{exact:true})
  await expect(field).toHaveValue('0')
  await expect(page.getByRole('button',{name:'Preparar análise',exact:false})).toBeDisabled()
  await field.fill('4')
  await page.getByRole('button',{name:'Salvar limites',exact:true}).click()
  await page.reload()
  await page.getByText('Ajustar limites e pausar',{exact:true}).click()
  await expect(field).toHaveValue('4')
  const state=await(await context.request.get('/api/ai/settings')).json()
  expect(state.authorized_total_usd).toBe(4)
  expect(state.usage.total_usd).toBe(0)
  expect(state.key_configured).toBeFalsy()
  await context.request.put('/api/ai/key',{headers:{Origin:origin},data:{key:'synthetic-not-a-provider-key'}})
  await page.reload()
  await page.getByText('Credencial da API',{exact:true}).click()
  await page.getByRole('button',{name:'Remover chave deste PC e pausar',exact:true}).click()
  await expect(page.getByRole('status')).toContainText('Chave removida e chamadas pausadas.')
  const removed=await(await context.request.get('/api/ai/settings')).json()
  expect(removed.key_configured).toBeFalsy()
  expect(removed.limits.enabled).toBeFalsy()
  expect(removed.authorized_total_usd).toBe(4)
  const audit=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
  expect(audit.violations.map(v=>v.id)).toEqual([])
  await page.screenshot({path:test.info().outputPath('budget.png'),fullPage:true})
})
