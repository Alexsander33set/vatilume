test('sparse temperature readings remain visible without joining empty intervals',async({page})=>{
  await page.route('**/api/overview?*',async route=>{
    const response=await route.fetch()
    const data=await response.json()
    const step=(data.window.end_ms-data.window.start_ms)/240
    data.sample_count=Math.max(2,data.sample_count)
    data.series=Array.from({length:240},(_,i)=>({time_ms:data.window.start_ms+(i+.5)*step,...(i%2===0?{cpu_temp:50+i/100}:{gpu_temp:40+i/100})}))
    await route.fulfill({response,json:data})
  })
  await page.goto('/')
  await page.getByRole('button',{name:'Temperatura',exact:true}).click()
  const cpu=page.locator('[data-series="cpu_temp"]'),gpu=page.locator('[data-series="gpu_temp"]')
  await expect(cpu.locator('.chart-reading')).toHaveCount(120)
  await expect(gpu.locator('.chart-reading')).toHaveCount(120)
  await expect(cpu.locator('path')).toHaveAttribute('d','')
  await expect(gpu.locator('path')).toHaveAttribute('d','')
  await expect(page.locator('.chart-caption')).toContainText('Pontos mostram leituras isoladas')
  const chart=page.getByRole('group',{name:/Histórico de temperatura/})
  await chart.focus();await page.keyboard.press('ArrowRight')
  await expect(page.locator('.chart-caption')).toContainText('CPU sem leitura')
  await expect(page.locator('.chart-caption')).toContainText('GPU 40 °C')
  await expect(page.locator('.chart-cursor + .point-gpu')).toHaveCount(1)
  for(const width of [1440,390]){
    await page.setViewportSize({width,height:1000})
    await page.keyboard.press('Escape')
    await expect(cpu.locator('.chart-reading')).toHaveCount(120)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBeFalsy()
    await page.evaluate(()=>{(document.activeElement as HTMLElement)?.blur();window.scrollTo(0,0)})
    if(width<640)await expect.poll(async()=>page.locator('.sidebar').evaluate(element=>element.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
    await page.screenshot({path:`test-results/temperature-sparse-${width}.png`,fullPage:true,animations:'disabled'})
  }
})

